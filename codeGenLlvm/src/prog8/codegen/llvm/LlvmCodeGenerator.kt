package prog8.codegen.llvm

import prog8.code.ICodeGeneratorBackend
import prog8.code.SymbolTable
import prog8.code.assembly.IAssemblyProgram
import prog8.code.ast.PtProgram
import prog8.code.core.CompilationOptions
import prog8.code.core.IErrorReporter
import prog8.code.core.Position
import prog8.code.target.LlvmTarget
import prog8.codegen.intermediate.IRCodeGen
import prog8.codegen.llvm.lower.LlvmFunctionBuilder
import prog8.codegen.llvm.lower.LlvmGlobalEmitter
import prog8.codegen.llvm.lower.LlvmLoweringException
import prog8.codegen.llvm.model.LlvmModule
import prog8.intermediate.Calls
import prog8.intermediate.IRFileWriter
import prog8.intermediate.IRProgram
import prog8.intermediate.dumpVariables

/**
 * The code generator of the llvm targets: lowers the IR program to an LLVM module, which it saves as LLVM IR text.
 * IR that has no LLVM translation is reported as a compilation error.
 */
class LlvmCodeGenerator(private val retainSSA: Boolean) : ICodeGeneratorBackend {

    override fun generate(program: PtProgram, symbolTable: SymbolTable, options: CompilationOptions, errors: IErrorReporter): IAssemblyProgram? {
        val target = requireNotNull(options.compTarget as? LlvmTarget) { "the LLVM code generator needs the ${LlvmTarget.NAME32} or ${LlvmTarget.NAME64} target" }
        if (target.pointerSize != 8) {
            errors.err("code generation for the ${target.name} target is not implemented yet", Position.DUMMY)
            return null
        }
        val irCodeGen = IRCodeGen(program, symbolTable, options, errors, retainSSA)
        val irProgram = irCodeGen.generate()
        irProgram.verifyRegisterTypes(irCodeGen.registerTypes().entries.associate { (number, type) -> Calls.registerFor(number.value, type) to type })
        if (options.dumpVariables)
            dumpVariables(irProgram)
        IRFileWriter(irProgram, null).write()

        val module = try {
            module(irProgram, target, options)
        } catch (x: IllegalArgumentException) {
            errors.err(x.message ?: "the program can't be translated to LLVM IR", (x as? LlvmLoweringException)?.position ?: Position.DUMMY)
            return null
        }
        val (instructions, chunks) = irProgram.countCodeElements()
        return AssemblyProgramLlvm(irProgram.name, LlvmPrinter.print(module), instructions, chunks, irProgram.countUsedRegisters())
            .also { it.save(options) }
    }

    private fun module(irProgram: IRProgram, target: LlvmTarget, options: CompilationOptions): LlvmModule {
        val module = LlvmModule(irProgram.name, target.targetTriple, target.dataLayout)
        module.headerComments += "generated by Prog8 ${options.compilerVersion} for the ${target.name} target"
        LlvmFunctionBuilder(irProgram, LlvmGlobalEmitter(irProgram).emit(module)).buildProgram(module)
        return module
    }
}
