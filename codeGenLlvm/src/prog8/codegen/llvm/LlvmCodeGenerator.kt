/**
 * The code generator of the llvm targets: lowers the IR program to an LLVM module, which it saves as LLVM IR text.
 * IR that has no LLVM translation is reported as a compilation error.
 */
class LlvmCodeGenerator(private val retainSSA: Boolean) : ICodeGeneratorBackend {

    override fun generate(program: PtProgram, symbolTable: SymbolTable, options: CompilationOptions, errors: IErrorReporter): IAssemblyProgram? {
        val target = requireNotNull(options.compTarget as? LlvmTarget) { "the LLVM code generator needs an llvm target" }
        if (!target.supportsFloats && reportFloats(program, errors))
            return null
        val irCodeGen = IRCodeGen(program, symbolTable, options, errors, retainSSA)
        val irProgram = irCodeGen.generate()
        irProgram.verifyRegisterTypes(irCodeGen.registerTypes().entries.associate { (number, type) -> Calls.registerFor(number.value, type) to type })
        if (options.dumpVariables)
            dumpVariables(irProgram)
        IRFileWriter(irProgram, null).write()
        return generateFromIR(irProgram, errors)
    }

    /** The LLVM IR of an [IRProgram], also one read from a .p8ir file, whose options name the llvm target. */
    fun generateFromIR(irProgram: IRProgram, errors: IErrorReporter): IAssemblyProgram? {
        val options = irProgram.options
        val target = requireNotNull(options.compTarget as? LlvmTarget) { "the LLVM code generator needs an llvm target" }
        val module = try {
            module(irProgram, target, options, errors)
        } catch (x: IllegalArgumentException) {
            errors.err(x.message ?: "the program can't be translated to LLVM IR", (x as? LlvmLoweringException)?.position ?: Position.DUMMY)
            return null
        }
        val (instructions, chunks) = irProgram.countCodeElements()
        return AssemblyProgramLlvm(irProgram.name, LlvmPrinter.print(module), instructions, chunks, irProgram.countUsedRegisters())
            .also { it.save(options) }
    }

    /** Reports the nodes that use floats, which the AstChecker can't all see, such as a float cast; true when there are any. */
    private fun reportFloats(program: PtProgram, errors: IErrorReporter): Boolean {
        var found = false
        walkAst(program) { node, _ ->
            val type = when (node) {
                is PtExpression -> node.type
                is IPtVariable -> node.type
                is PtSubroutineParameter -> node.type
                is PtSubSignature -> node.returns.firstOrNull { it.isFloat }
                else -> null
            }
            val float = type != null && (type.isFloat || type.isFloatArray)
            if (float) {
                errors.err(LlvmTarget.FLOATS_UNSUPPORTED, node.position)
                found = true
            }
            !float
        }
        return found
    }

    private fun module(irProgram: IRProgram, target: LlvmTarget, options: CompilationOptions, errors: IErrorReporter): LlvmModule {
        val module = LlvmModule(irProgram.name, target.targetTriple, target.dataLayout, functionAttributes = target.functionAttributes)
        module.headerComments += "generated by Prog8 ${options.compilerVersion} for the ${target.name} target"
        val stackLocals = StackLocals(irProgram)
        for ((sub, shared) in stackLocals.sharedByRecursion()) {
            val names = shared.joinToString { "'${it.name.removePrefix(sub.label + ".")}'" }
            errors.warn("recursive subroutine '${sub.label.substringAfterLast('.')}' keeps $names in static storage, which its recursive calls share", sub.position)
        }
        LlvmFunctionBuilder(irProgram, LlvmGlobalEmitter(irProgram, stackLocals.owners).emit(module)).buildProgram(module)
        return module
    }
}
